final class SlugTests: XCTestCase {
    func testMakesReadableSlugs() {
        XCTAssertEqual(Slug.make(from: "Work"), "work")
        XCTAssertEqual(Slug.make(from: "Client – Acme"), "client-acme")
        XCTAssertEqual(Slug.make(from: "Công việc"), "cong-viec")
        XCTAssertEqual(Slug.make(from: "Đức's Team!"), "duc-s-team")
        XCTAssertEqual(Slug.make(from: "  "), "profile")
    }

    func testUniqueAddsNumber() {
        XCTAssertEqual(Slug.unique("work", taken: []), "work")
        XCTAssertEqual(Slug.unique("work", taken: ["work"]), "work-2")
        XCTAssertEqual(Slug.unique("work", taken: ["work", "work-2"]), "work-3")
    }
}

final class ProfileTests: XCTestCase {
    private func profile(_ name: String, slug: String) -> Profile {
        Profile(id: UUID(), name: name, colorHex: "#2563EB", slug: slug, commandEnabled: true,
                commandName: nil, builtClaudeVersion: "1.0.0")
    }

    func testDerivedValues() {
        let work = profile("work", slug: "work")
        XCTAssertEqual(work.letter, "W")
        XCTAssertEqual(work.displayName, "Claude work")
        XCTAssertEqual(work.defaultCommandName, "claude-work")
        XCTAssertTrue(work.bundleID.hasSuffix(".profile.work"))
        XCTAssertEqual(work.appURL.lastPathComponent, "Claude work.app")
        XCTAssertTrue(Paths.isManagedAppLocation(work.appURL))
        XCTAssertEqual(work.desktopDataDirectory.lastPathComponent, "Desktop")
        XCTAssertEqual(work.claudeCodeDirectory.lastPathComponent, "ClaudeCode")
    }

    func testSlashesInNamesStayInsideProfileFolder() {
        let odd = profile("a/b:c", slug: "a-b-c")
        XCTAssertTrue(Paths.isManagedAppLocation(odd.appURL))
    }

    func testNeedsRebuild() {
        let work = profile("Work", slug: "work")
        XCTAssertFalse(work.needsRebuild(currentClaudeVersion: "1.0.0"))
        XCTAssertTrue(work.needsRebuild(currentClaudeVersion: "1.1.0"))
        XCTAssertFalse(work.needsRebuild(currentClaudeVersion: nil))
    }

    func testOriginalClaudeIsNeverAManagedLocation() {
        XCTAssertFalse(Paths.isManagedAppLocation(URL(fileURLWithPath: "/Applications/Claude.app")))
        XCTAssertFalse(Paths.isManagedAppLocation(Paths.home.appendingPathComponent("Applications/Claude.app")))
    }
}

final class StoredBundleIDTests: XCTestCase {
    func testOldProfilesFileStillDecodes() throws {
        let json = ##"{"version":1,"profiles":[{"id":"6F9619FF-8B86-D011-B42D-00C04FC964FF","name":"Work","colorHex":"#2563EB","slug":"work","commandEnabled":true,"commandName":"claude-work","builtClaudeVersion":"1.0.0"}]}"##
        struct File: Decodable { let profiles: [Profile] }
        let profile = try XCTUnwrap(JSONDecoder().decode(File.self, from: Data(json.utf8)).profiles.first)
        XCTAssertNil(profile.storedBundleID)
        XCTAssertEqual(profile.bundleID, Profile.bundleID(for: "work"))
    }

    func testStoredBundleIDIsSavedAndWins() throws {
        var profile = Profile(id: UUID(), name: "Work", colorHex: "#2563EB", slug: "work", commandEnabled: false,
                              commandName: nil, builtClaudeVersion: nil)
        profile.storedBundleID = "com.example.other.profile.work"
        XCTAssertEqual(profile.bundleID, "com.example.other.profile.work")
        let data = try JSONEncoder().encode(profile)
        XCTAssertTrue(String(decoding: data, as: UTF8.self).contains(#""bundleID":"com.example.other.profile.work""#))
        XCTAssertEqual(try JSONDecoder().decode(Profile.self, from: data).bundleID, "com.example.other.profile.work")
    }

    func testMigrationFillsOnlyMissingIDs() {
        let missing = Profile(id: UUID(), name: "Nowhere", colorHex: "#2563EB", slug: "mpfc-no-such-profile",
                              commandEnabled: false, commandName: nil, builtClaudeVersion: nil)
        var kept = missing
        kept.storedBundleID = "com.example.kept"
        let result = ProfileStore.withBundleIDs([missing, kept])
        XCTAssertTrue(result.changed)
        XCTAssertEqual(result.profiles[0].storedBundleID, Profile.bundleID(for: "mpfc-no-such-profile"))
        XCTAssertEqual(result.profiles[1].storedBundleID, "com.example.kept")
        XCTAssertFalse(ProfileStore.withBundleIDs(result.profiles).changed)
    }
}

final class BuildDefaultsTests: XCTestCase {
    /// BuildDefaults.swift is generated by scripts/build.sh; this catches a config.sh change
    /// that wasn't followed by a build.
    func testMatchesConfig() throws {
        let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let script = "source scripts/config.sh && printf '%s\\n' \"$BUNDLE_ID\" \"$REPO_URL\" \"$DONATE_URL\" \"$DONATE_BANK\" \"$DONATE_ACCOUNT_NAME\" \"$DONATE_ACCOUNT_NUMBER\""
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/bash")
        process.arguments = ["-c", script]
        process.currentDirectoryURL = root
        let pipe = Pipe()
        process.standardOutput = pipe
        try process.run()
        process.waitUntilExit()
        let values = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
            .split(separator: "\n").map(String.init)
        XCTAssertEqual(values, [BuildDefaults.bundleIDPrefix, BuildDefaults.repositoryURL, BuildDefaults.donateURL,
                                BuildDefaults.donateBank, BuildDefaults.donateAccountName, BuildDefaults.donateAccountNumber],
                       "Run scripts/build.sh to regenerate BuildDefaults.swift from scripts/config.sh")
    }
}

