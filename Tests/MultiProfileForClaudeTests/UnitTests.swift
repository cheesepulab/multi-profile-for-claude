final class CommandTests: XCTestCase {
    func testScriptContent() {
        let profile = Profile(id: UUID(), name: "Work \"A\"", colorHex: "#2563EB", slug: "work-a",
                              commandEnabled: true, commandName: nil, builtClaudeVersion: nil)
        let script = CLICommandInstaller().script(for: profile)
        XCTAssertTrue(script.hasPrefix("#!/bin/sh\n"))
        XCTAssertTrue(script.contains(CLICommandInstaller.marker))
        XCTAssertTrue(script.contains("export CLAUDE_CONFIG_DIR=\"$HOME/Library/Application Support/MultiProfileForClaude/Profiles/work-a/ClaudeCode\""))
        XCTAssertTrue(script.contains("exec claude \"$@\""))
        XCTAssertFalse(script.contains("\"A\""), "quotes in the profile name must not break the script")
    }

    func testCommandNameValidation() {
        let installer = CLICommandInstaller()
        XCTAssertTrue(installer.isValid("claude-work"))
        XCTAssertFalse(installer.isValid("claude"))
        XCTAssertFalse(installer.isValid("-rf"))
        XCTAssertFalse(installer.isValid("../x"))
        XCTAssertFalse(installer.isValid("a b"))
    }
}
